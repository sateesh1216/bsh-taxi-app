export type Lang = "en" | "te" | "hi";
export type { Key };
const DICT: Record<Lang, Partial<Record<Key, string>>> = { en, te, hi };
const STORE = "bsh_lang_v1";

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string };
const LangContext = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (k) => en[k] });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const [ready, setReady] = useState(false);
  useEffect(() => {
    let active = true;
    AsyncStorage.getItem(STORE).then((v) => {
      if (active && (v === "en" || v === "te" || v === "hi")) setLangState(v);
    }).catch(() => {}).finally(() => { if (active) setReady(true); });
    return () => { active = false; };
  }, []);
  const value = useMemo<Ctx>(() => ({
    lang,
    setLang: (l) => {
      setLangState(l);
      AsyncStorage.setItem(STORE, l).catch(() => {});
    },
    t: (k) => DICT[lang][k] ?? en[k],
  }), [lang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export const useT = () => useContext(LangContext);
